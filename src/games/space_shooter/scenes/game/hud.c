void hud_init(void) {
    set_bkg_data(BLANK_TILE_INDEX, 1, blank_tile);
    set_bkg_data(HUD_TILE_BASE, HUD_TILE_COUNT, hud_tiles);
    fill_win_rect(0, 0, 20, 18, BLANK_TILE_INDEX);
    move_win(7, 0);
    SHOW_WIN;
}

void hud_render(const shooter_game_st* shooter_st) {
    UINT8 row[HUD_ROW_WIDTH];
    UINT8 i;
    UINT16 score = shooter_st->score;

    for (i = 0; i < HUD_ROW_WIDTH; i++)
        row[i] = BLANK_TILE_INDEX;

    row[0] = (UINT8)(HUD_DIGIT_BASE + ((score / 1000) % HUD_DIGITS_COUNT));
    row[1] = (UINT8)(HUD_DIGIT_BASE + ((score / 100) % HUD_DIGITS_COUNT));
    row[2] = (UINT8)(HUD_DIGIT_BASE + ((score / 10) % HUD_DIGITS_COUNT));
    row[3] = (UINT8)(HUD_DIGIT_BASE + (score % HUD_DIGITS_COUNT));

    row[8] = (UINT8)(HUD_DIGIT_BASE + ((shooter_st->wave / 10) % HUD_DIGITS_COUNT));
    row[9] = (UINT8)(HUD_DIGIT_BASE + (shooter_st->wave % HUD_DIGITS_COUNT));

    for (i = 0; i < shooter_st->lives && i < SHOOTER_INITIAL_LIVES; i++)
        row[HUD_ROW_WIDTH - 1 - i] = (UINT8)HUD_HEART_TILE;

    set_win_tiles(0, 0, HUD_ROW_WIDTH, 1, row);
}